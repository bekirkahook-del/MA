import json, os
S = lambda pairs: "Sources: " + " · ".join(f'<a href="{u}" rel="nofollow">{n}</a>' for n, u in pairs)
_W = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "data", "wire.json"), encoding="utf-8"))
def when(bank):
    for a in _W.get("APP_OPEN", []):
        if a[0] == bank and "Summer" in a[1]:
            return f'M&amp;A Prep\'s <a href="/#recruit">application tracker</a> lists the {a[1]} as <b>{a[5]}</b>. Postings can open and close early, so check the bank\'s careers site often.'
    return 'Track openings on M&amp;A Prep\'s <a href="/#recruit">application tracker</a>.'

