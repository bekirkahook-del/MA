// Generates one bot file per entry in specA/specB (each bot keeps its own file, its own header and its own CLI), plus circle/pack3.mjs (the metadata the circle and the Obsidian notes read).
// Run: node tools/bots/flywheel/gen.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { A } from "./specA.mjs";
import { B } from "./specB.mjs";
const here = path.dirname(fileURLToPath(import.meta.url)), bots = path.join(here, ".."), all = [...A, ...B];
const header = b => `// ${b.name}: ${b.does}
// Part of the Content Flywheel and operator desk (gear: ${b.gear}). Read-only: it reads your own files, tells you what to do, and never posts, signs in or deploys.
// Usage: node tools/bots/${b.id}.mjs [tracks.json]
import fs from "node:fs";
import { ROOT, cli } from "./lib.mjs";
import { report } from "./scan.mjs";
import { eg, rule, imgSize } from "./scan2.mjs";
import { loadOps, daysAgo, dayNum, parseBlackouts, outreachWindow } from "./ops.mjs";
import * as FW from "./flywheel/core.mjs";
import * as COST from "./cost.mjs";
import { flatten } from "./qdata.mjs";
const { fly, total, best, hasViews, provisional, family, sim, planDay, PLATFORMS, parseWireDate } = FW;
`;
for (const b of all) {
  const src = `${header(b)}
export const ${b.id} = ${b.fn.toString()};
export const scan = (root = ROOT, o = {}) => ${b.id}(o.ctx || loadOps(root, o.now || new Date(), { cost: COST, qs: o.qs || null }));
cli(import.meta.url, a => scan(ROOT, { qs: a[0] ? flatten(JSON.parse(fs.readFileSync(a[0], "utf8")).tracks) : null }));
`;
  fs.writeFileSync(path.join(bots, b.id + ".mjs"), src);
}
const meta = all.map(b => ({ id: b.id, name: b.name, gear: b.gear, does: b.does }));
fs.writeFileSync(path.join(bots, "circle", "pack3.mjs"), `// Generated by tools/bots/flywheel/gen.mjs. The Content Flywheel and operator desk: ${all.length} bots. Do not edit by hand.\nexport const PACK3 = ${JSON.stringify(meta, null, 1)};\n`);
console.log("wrote", all.length, "bots");
