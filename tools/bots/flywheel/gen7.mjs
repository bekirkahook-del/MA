// Generates the grow pack: one file per bot in tools/bots plus circle/pack7.mjs. Bot logic lives in flywheel/growdefs.mjs.
// Run: node tools/bots/flywheel/gen7.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { GROW } from "./growdefs.mjs";
const here = path.dirname(fileURLToPath(import.meta.url)), bots = path.join(here, "..");
const seen = new Set();
for (const b of GROW) {
  if (seen.has(b.id)) throw new Error("duplicate id " + b.id); seen.add(b.id);
  fs.writeFileSync(path.join(bots, b.id + ".mjs"), `// ${b.name}: ${b.does}
// Part of the grow pack. Read-only: it reads anonymous numbers and your own files. It never posts, sends, deploys or signs in.
// Usage: node tools/bots/${b.id}.mjs
import { ROOT, cli } from "./lib.mjs";
import { loadOps } from "./ops.mjs";
import * as COST from "./cost.mjs";
import { GROW } from "./flywheel/growdefs.mjs";
export const ${b.id} = GROW.find(b => b.id === ${JSON.stringify(b.id)}).fn;
export const scan = (root = ROOT, o = {}) => ${b.id}(o.ctx || loadOps(root, o.now || new Date(), { cost: COST }));
cli(import.meta.url, () => scan(ROOT));
`);
}
fs.writeFileSync(path.join(bots, "circle", "pack7.mjs"), `// Generated by tools/bots/flywheel/gen7.mjs. The grow pack: ${GROW.length} bots. Do not edit by hand.\nexport const PACK7 = ${JSON.stringify(GROW.map(({ id, name, gear, does }) => ({ id, name, gear, does })), null, 1)};\n`);
console.log("wrote", GROW.length, "bots");
