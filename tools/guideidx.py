"""Builds js/guideidx.js: every guide's slug + title, so the site search (Ctrl K) can find guides.
Run after adding or regenerating guides:  python3 tools/guideidx.py   (safe to rerun)"""
import os, re, html, json
root = os.path.join(os.path.dirname(__file__), "..")
rows = []
for slug in sorted(os.listdir(os.path.join(root, "guides"))):
    f = os.path.join(root, "guides", slug, "index.html")
    if slug.startswith("_") or not os.path.isfile(f):
        continue
    t = open(f, encoding="utf-8", errors="ignore").read(20000)
    m = re.search(r"<h1[^>]*>(.*?)</h1>", t, re.S) or re.search(r"<title>(.*?)</title>", t, re.S)
    title = html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).strip() if m else slug.replace("-", " ")
    title = re.sub(r"\s*[|·–-]\s*M&A Prep\s*$", "", title)
    rows.append(slug + "|" + re.sub(r"\s+", " ", title))
open(os.path.join(root, "js", "guideidx.js"), "w").write(
    "/* generated by tools/guideidx.py: guide slug|title for site search */\nwindow.GUIDE_IDX=" + json.dumps("\n".join(rows)) + ";\n")
print(len(rows), "guides indexed")
